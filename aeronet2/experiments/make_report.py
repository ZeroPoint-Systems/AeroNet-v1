"""Build results/RESULTS.md and figures from the raw JSON so documentation numbers can never drift."""
import json, os, sys
import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

R = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "results")
L = json.load(open(os.path.join(R, "law_manoeuvre_sweep.json")))
Fr = json.load(open(os.path.join(R, "frontier_ablation.json")))
md = ["# Results (auto-generated by experiments/make_report.py)\n",
      f"Law sweep seeds: {L['seeds']} | Frontier seeds: {Fr['seeds']}. All comparisons are paired per seed (common random numbers).\n"]

# ------------------------------------------------------------------ law
rows = [r for r in L["rows"] if r["mu"] > 0]
mu = np.array([r["mu"] for r in rows])
G = {p: -np.array([r["vs_periodic_" + p]["rel_diff"] for r in rows]) for p in ("voi_psa", "innov", "voi_fb")}


def fit(m, g):
    ok = g > 0
    b, a = np.polyfit(np.log(m[ok]), np.log(g[ok]), 1)
    pred = np.exp(a) * m[ok] ** b
    ss_res = np.sum((np.log(g[ok]) - np.log(pred)) ** 2); ss_tot = np.sum((np.log(g[ok]) - np.log(g[ok]).mean()) ** 2)
    return np.exp(a), b, 1 - ss_res / ss_tot


md.append("## 1. Mismatch law: relative gain of adaptive communication over periodic\n")
md.append("| rate | acc | mu = duty*acc^2 | periodic RMSE | voi_psa gain | 95% CI | innov gain | voi_fb gain | equiv. to periodic (+/-1%)? |\n|---|---|---|---|---|---|---|---|---|")
for r in L["rows"]:
    v = r["vs_periodic_voi_psa"]
    md.append("| %.3f | %.2f | %.4f | %.3f | %+.1f%% | [%+.1f, %+.1f]%% | %+.1f%% | %+.1f%% | %s |" % (
        r["rate"], r["acc"], r["mu"], r["rmse"]["periodic"], -100 * v["rel_diff"], -100 * v["ci_hi"] / r["rmse"]["periodic"],
        -100 * v["ci_lo"] / r["rmse"]["periodic"], -100 * -r["vs_periodic_innov"]["rel_diff"] * -1 if False else -100 * r["vs_periodic_innov"]["rel_diff"],
        -100 * r["vs_periodic_voi_fb"]["rel_diff"], "yes" if v.get("equivalent_within_margin") else "no"))
res = {}
for p, g in G.items():
    if (g > 0).sum() < 3:
        md.append(f"\n**{p}:** gain is not positive in enough configurations to fit a law (mean gain {100*g.mean():+.1f}%).")
        continue
    a, b, r2 = fit(mu, g); res[p] = (a, b, r2)
    md.append(f"\n**Power-law fit, {p}:** gain = {a:.3f} * mu^{b:.2f}  (log-space R^2 = {r2:.2f}, {len(mu)} configurations).")
# post-hoc (exploratory) alternative predictor: variability of mismatch power over time, acc^2*sqrt(duty*(1-duty))
nu = np.array([r["acc"] ** 2 * np.sqrt(r["duty"] * (1 - r["duty"])) for r in rows])
a_nu, b_nu, r2_nu = fit(nu, G["voi_psa"])
a_mu, b_mu, r2_mu = res["voi_psa"]
md.append(f"\n**Predictor comparison for voi_psa gain (log-space R^2):** mean mismatch mu: {r2_mu:.2f}; "
          f"mismatch *variability* nu = acc^2*sqrt(duty(1-duty)): {r2_nu:.2f}  [nu was proposed after seeing the data -> exploratory; "
          f"see confirmatory run]. nu-fit: gain = {a_nu:.3f} * nu^{b_nu:.2f}")
json.dump(dict(mu=dict(a=a_mu, b=b_mu, r2=r2_mu), nu=dict(a=a_nu, b=b_nu, r2=r2_nu)), open(os.path.join(R, "law_fit.json"), "w"))
# held-out validation: fit on the 6 mildest configs, predict the strongest 3
order = np.argsort(mu); tr, te = order[:-3], order[-3:]
a, b, _ = fit(mu[tr], G["voi_psa"][tr])
pred = a * mu[te] ** b
md.append("\n**Held-out check (voi_psa):** fit on the %d mildest configs, predict the %d strongest: " % (len(tr), len(te)) +
          ", ".join("mu=%.3f predicted %.1f%% observed %.1f%%" % (m, 100 * p_, 100 * o) for m, p_, o in zip(mu[te], pred, G["voi_psa"][te])))
nom = [r for r in L["rows"] if r["mu"] == 0][0]
md.append("\n**Null regime (no manoeuvres):** voi_psa vs periodic = %+.2f%% [%+.2f, %+.2f]%% (equivalent within 1%%: %s)\n" % (
    100 * nom["vs_periodic_voi_psa"]["rel_diff"], 100 * nom["vs_periodic_voi_psa"]["ci_lo"] / nom["rmse"]["periodic"],
    100 * nom["vs_periodic_voi_psa"]["ci_hi"] / nom["rmse"]["periodic"], nom["vs_periodic_voi_psa"].get("equivalent_within_margin")))
fig, ax = plt.subplots(figsize=(5.2, 3.6))
for p, c in (("voi_psa", "C0"), ("innov", "C1"), ("voi_fb", "C2")):
    ax.loglog(mu, np.clip(100 * G[p], 1e-3, None), "o", color=c, label=p)
    if p not in res: continue
    a, b, _ = res[p]; xs = np.logspace(np.log10(mu.min()), np.log10(mu.max()), 20); ax.loglog(xs, 100 * a * xs ** b, "-", color=c, alpha=.5)
ax.set_xlabel("mismatch index mu = duty x acc^2"); ax.set_ylabel("RMSE reduction vs periodic (%)"); ax.legend(); ax.grid(alpha=.3)
fig.tight_layout(); fig.savefig(os.path.join(R, "fig_law.png"), dpi=150)

# ------------------------------------------------------------------ frontier / ablation
md.append("\n## 2. Frontier and ablation ladder (paired vs periodic, Holm-adjusted over the non-trivial policies)\n")
for scen, byB in Fr["results"].items():
    md.append(f"\n### {scen}\n")
    md.append("| budget | policy | RMSE | msgs/agent | bytes/agent | vs periodic | 95% CI (abs) | p (Holm) | NEES |\n|---|---|---|---|---|---|---|---|---|")
    for B, cell in byB.items():
        for p in Fr["policies"]:
            c = cell[p]; v = c["vs_periodic"]
            md.append("| %s | %s | %.3f | %.1f | %.0f | %s | %s | %s | %.2f |" % (
                B, p, c["rmse"], c["sent"], c["bytes"] / 6,
                "-" if v is None else "%+.1f%%" % (100 * v["rel_diff"]),
                "-" if v is None else "[%+.3f, %+.3f]" % (v["ci_lo"], v["ci_hi"]),
                "-" if v is None or "p_holm" not in v else "%.3g" % v["p_holm"], c["nees"]))
fig, axs = plt.subplots(1, 2, figsize=(9, 3.6), sharey=False)
for ax, (scen, byB) in zip(axs, Fr["results"].items()):
    for p, mk in (("periodic", "o-"), ("voi_psa", "s-"), ("innov", "^--"), ("random", "x:"), ("ci_periodic", "d:")):
        Bs = list(byB.keys())
        ax.plot([byB[B][p]["sent"] for B in Bs], [byB[B][p]["rmse"] for B in Bs], mk, label=p)
    b0 = byB[list(byB)[0]]
    ax.axhline(b0["none"]["rmse"], color="k", ls=":", lw=1); ax.axhline(b0["broadcast"]["rmse"], color="g", ls=":", lw=1)
    ax.set_title(scen); ax.set_xlabel("messages sent per agent"); ax.set_xscale("log"); ax.grid(alpha=.3)
axs[0].set_ylabel("steady-state position RMSE"); axs[0].legend(fontsize=7)
fig.tight_layout(); fig.savefig(os.path.join(R, "fig_frontier.png"), dpi=150)
open(os.path.join(R, "RESULTS.md"), "w").write("\n".join(md) + "\n")
print("\n".join(md[:30]))
